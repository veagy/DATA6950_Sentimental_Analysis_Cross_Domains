class FeatureUnion(MLTransform):
    """
    Concatenates results of multiple transformer objects.

    This estimator applies a list of transformer objects in parallel to the
    input data, then concatenates the results. This is useful to combine
    several feature extraction mechanisms into a single transformer.

    Parameters of the transformers may be set using its name and the parameter
    name separated by a '__'. A transformer may be replaced entirely by
    setting the parameter with its name to another transformer, removed by
    setting to 'drop' or disabled by setting to 'passthrough' (features are
    passed without transformation).

    Read more in the :ref:`User Guide <feature_union>`.

    .. versionadded:: 0.13

    Parameters
    ----------
    transformer_list : list of (str, transformer) tuples
        List of transformer objects to be applied to the data. The first
        half of each tuple is the name of the transformer. The transformer can
        be 'drop' for it to be ignored or can be 'passthrough' for features to
        be passed unchanged.

        .. versionadded:: 1.1
           Added the option `"passthrough"`.

        .. versionchanged:: 0.22
           Deprecated `None` as a transformer in favor of 'drop'.

    n_jobs : int, default=None
        Number of jobs to run in parallel.
        ``None`` means 1 unless in a :obj:`joblib.parallel_backend` context.
        ``-1`` means using all processors. See :term:`Glossary <n_jobs>`
        for more details.

        .. versionchanged:: v0.20
           `n_jobs` default changed from 1 to None

    transformer_weights : dict, default=None
        Multiplicative weights for features per transformer.
        Keys are transformer names, values the weights.
        Raises ValueError if key not present in ``transformer_list``.

    verbose : bool, default=False
        If True, the time elapsed while fitting each transformer will be
        printed as it is completed.

    verbose_feature_names_out : bool, default=True
        If True, :meth:`get_feature_names_out` will prefix all feature names
        with the name of the transformer that generated that feature.
        If False, :meth:`get_feature_names_out` will not prefix any feature
        names and will error if feature names are not unique.

        .. versionadded:: 1.5

    Attributes
    ----------
    named_transformers : :class:`~sklearn.utils.Bunch`
        Dictionary-like object, with the following attributes.
        Read-only attribute to access any transformer parameter by user
        given name. Keys are transformer names and values are
        transformer parameters.

        .. versionadded:: 1.2

    n_features_in_ : int
        Number of features seen during :term:`fit`. Only defined if the
        underlying first transformer in `transformer_list` exposes such an
        attribute when fit.
    """
    def __init__(self,
                 transformers: Union[List[Union[list, tuple]],
                     Tuple[List[Union[list, tuple]]],
                     torch.Tensor,
                     None] = None,
                 n_jobs: int = None,
                 transformer_weights: dict = None,
                 verbose: bool = False,
                 verbose_feature_names_out: Union[bool, str, Callable[[str, str], str]] = True,
                 device: Union[str, torch.device] = "cpu",
                 dtype: torch.dtype = torch.float,
                 *args,
                 **kwargs,
                 ):
        super().__init__()
        self.transformers = list(transformers) if transformers is not None else []
        self.n_jobs = n_jobs
        self.transformer_weights = transformer_weights or {}
        self.verbose = verbose
        self.verbose_feature_names_out = verbose_feature_names_out
        self.device = (torch.device(device)
                       if isinstance(device, str) else device)
        self.dtype = dtype
        self.args = args
        self.kwargs = kwargs

        # Validate transformer_weights keys
        t_names = {entry[0] for entry in self.transformers}
        for k in self.transformer_weights:
            if k not in t_names:
                raise ValueError(
                    f"transformer_weights key {k!r} not found in transformer_list."
                )

        # Fitted attributes
        self.named_transformers: Dict[str, Any] = {}
        self.n_features_in_: Optional[int] = None
        self.fit_status = False

    # ------------------------------------------------------------------
    def fit(self, X: Any, y: Any = None, **kwargs) -> "FeatureUnion":
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)
        self.n_features_in_ = X_t.shape[1]

        for entry in self.transformers:
            t_name, t = entry[0], entry[1]
            if t in ("drop", "passthrough", None):
                self.named_transformers[t_name] = t
                continue
            t0 = time.time() if self.verbose else None
            t.fit(X_t, y)
            self.named_transformers[t_name] = t
            if self.verbose:
                print(f"[FeatureUnion] Fitting {t_name!r} done in "
                      f"{time.time() - t0:.3f}s")

        self.fit_status = True
        return self

    # ------------------------------------------------------------------
    def transform(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            raise RuntimeError("Call fit() before transform().")
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        parts: List[torch.Tensor] = []
        for entry in self.transformers:
            t_name, t = entry[0], entry[1]
            if t is None or t == "drop":
                continue
            if t == "passthrough":
                out = X_t
            else:
                out = t.transform(X_t)
                if isinstance(out, torch.Tensor) and out.is_sparse:
                    out = out.to_dense()
            out = out.to(dtype=self.dtype, device=self.device)
            if out.ndim == 1:
                out = out.unsqueeze(1)
            w = self.transformer_weights.get(t_name)
            if w is not None:
                out = out * w
            parts.append(out)

        if not parts:
            return torch.zeros(X_t.shape[0], 0,
                               dtype=self.dtype, device=self.device)
        return torch.cat(parts, dim=1)

    # ------------------------------------------------------------------
    def fit_transform(self, X: Any, y: Any = None, **kwargs) -> torch.Tensor:
        return self.fit(X, y, **kwargs).transform(X, **kwargs)

    # ------------------------------------------------------------------
    def get_feature_names_out(
        self, input_features: Optional[List[str]] = None
    ) -> List[str]:
        if not self.fit_status:
            raise RuntimeError("Call fit() before get_feature_names_out().")
        vfno = self.verbose_feature_names_out
        all_names: List[str] = []

        for entry in self.transformers:
            t_name, t = entry[0], entry[1]
            if t is None or t == "drop":
                continue
            if t == "passthrough":
                sub = (input_features if input_features
                       else [f"x{i}" for i in range(self.n_features_in_)])
            elif hasattr(t, "get_feature_names_out"):
                sub = list(t.get_feature_names_out())
            else:
                sub = [f"{t_name}_feat{i}" for i in range(
                    getattr(t, "n_output_features_", 1))]

            for fn in sub:
                if vfno is True:
                    all_names.append(f"{t_name}__{fn}")
                elif vfno is False:
                    all_names.append(fn)
                elif isinstance(vfno, str):
                    all_names.append(
                        vfno.format(transformer_name=t_name, feature_name=fn))
                elif callable(vfno):
                    all_names.append(vfno(t_name, fn))
                else:
                    all_names.append(fn)

        # Check uniqueness when verbose_feature_names_out=False
        if vfno is False and len(all_names) != len(set(all_names)):
            raise ValueError(
                "Feature names are not unique. Set "
                "verbose_feature_names_out=True to prefix feature names."
            )
        return all_names

    # ------------------------------------------------------------------
    def forward(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            self.fit(X, **kwargs)
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def predict(self, X: Any, **kwargs) -> torch.Tensor:
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def score(self, X: Any, y: Any = None, **kwargs) -> float:
        return 0.0

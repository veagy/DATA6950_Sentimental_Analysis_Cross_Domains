def _apply_tree(node: Dict, X: torch.Tensor
                ) -> Tuple[torch.Tensor, int]:
    """
    Traverse a fitted decision-tree structure for each sample in X.

    Returns
    -------
    leaf_ids : (n_samples,) LongTensor  — per-sample leaf index (0-based)
    n_leaves : int                      — total number of leaves
    """
    # First pass: assign a unique integer ID to every leaf node (DFS order)
    leaf_id_map: Dict[int, int] = {}

    def _assign(node: Dict, nxt: int) -> int:
        if node.get("leaf", False):
            leaf_id_map[id(node)] = nxt
            return nxt + 1
        nxt = _assign(node["left"], nxt)
        nxt = _assign(node["right"], nxt)
        return nxt

    n_leaves = _assign(node, 0)

    # Second pass: route each sample to its leaf
    def _route(x: torch.Tensor, nd: Dict) -> int:
        if nd.get("leaf", False):
            return int(leaf_id_map[id(nd)])
        feat_idx = int(nd["feature"]) if isinstance(nd["feature"], (torch.Tensor, np.integer)) else nd["feature"]
        thresh = nd["threshold"]
        if isinstance(thresh, torch.Tensor):
            thresh = thresh.item()
        if x[feat_idx].item() <= thresh:
            return _route(x, nd["left"])
        return _route(x, nd["right"])

    n = int(X.shape[0])
    leaf_ids = torch.zeros(n, dtype=torch.long, device=X.device)
    for i in range(n):
        leaf_ids[i] = int(_route(X[i], node))

    return leaf_ids, n_leaves


class RandomTreesEmbeddings(MLTransform):
    """
    An ensemble of totally random trees.

    An unsupervised transformation of a dataset to a high-dimensional
    sparse representation. A datapoint is coded according to which leaf of
    each tree it is sorted into. Using a one-hot encoding of the leaves,
    this leads to a binary coding with as many ones as there are trees in
    the forest.

    The dimensionality of the resulting representation is
    ``n_out <= n_estimators * max_leaf_nodes``. If ``max_leaf_nodes == None``,
    the number of leaf nodes is at most ``n_estimators * 2 ** max_depth``.

    For an example of applying Random Trees Embedding to non-linear
    classification, see
    :ref:`sphx_glr_auto_examples_ensemble_plot_random_forest_embedding.py`.

    Read more in the :ref:`User Guide <random_trees_embedding>`.

    Parameters
    ----------
    n_estimators : int, default=100
        Number of trees in the forest.

        .. versionchanged:: 0.22
           The default value of ``n_estimators`` changed from 10 to 100
           in 0.22.

    max_depth : int, default=5
        The maximum depth of each tree. If None, then nodes are expanded until
        all leaves are pure or until all leaves contain less than
        min_samples_split samples.

    min_samples_split : int or float, default=2
        The minimum number of samples required to split an internal node:

        - If int, then consider `min_samples_split` as the minimum number.
        - If float, then `min_samples_split` is a fraction and
          `ceil(min_samples_split * n_samples)` is the minimum
          number of samples for each split.

        .. versionchanged:: 0.18
           Added float values for fractions.

    min_samples_leaf : int or float, default=1
        The minimum number of samples required to be at a leaf node.
        A split point at any depth will only be considered if it leaves at
        least ``min_samples_leaf`` training samples in each of the left and
        right branches.  This may have the effect of smoothing the model,
        especially in regression.

        - If int, then consider `min_samples_leaf` as the minimum number.
        - If float, then `min_samples_leaf` is a fraction and
          `ceil(min_samples_leaf * n_samples)` is the minimum
          number of samples for each node.

        .. versionchanged:: 0.18
           Added float values for fractions.

    min_weight_fraction_leaf : float, default=0.0
        The minimum weighted fraction of the sum total of weights (of all
        the input samples) required to be at a leaf node. Samples have
        equal weight when sample_weight is not provided.

    max_leaf_nodes : int, default=None
        Grow trees with ``max_leaf_nodes`` in best-first fashion.
        Best nodes are defined as relative reduction in impurity.
        If None then unlimited number of leaf nodes.

    min_impurity_decrease : float, default=0.0
        A node will be split if this split induces a decrease of the impurity
        greater than or equal to this value.

        The weighted impurity decrease equation is the following::

            N_t / N * (impurity - N_t_R / N_t * right_impurity
                                - N_t_L / N_t * left_impurity)

        where ``N`` is the total number of samples, ``N_t`` is the number of
        samples at the current node, ``N_t_L`` is the number of samples in the
        left child, and ``N_t_R`` is the number of samples in the right child.

        ``N``, ``N_t``, ``N_t_R`` and ``N_t_L`` all refer to the weighted sum,
        if ``sample_weight`` is passed.

        .. versionadded:: 0.19

    sparse_output : bool, default=True
        Whether or not to return a sparse CSR matrix, as default behavior,
        or to return a dense array compatible with dense pipeline operators.

    n_jobs : int, default=None
        The number of jobs to run in parallel. :meth:`fit`, :meth:`transform`,
        :meth:`decision_path` and :meth:`apply` are all parallelized over the
        trees. ``None`` means 1 unless in a :obj:`joblib.parallel_backend`
        context. ``-1`` means using all processors. See :term:`Glossary
        <n_jobs>` for more details.

    random_state : int, RandomState instance or None, default=None
        Controls the generation of the random `y` used to fit the trees
        and the draw of the splits for each feature at the trees' nodes.
        See :term:`Glossary <random_state>` for details.

    verbose : int, default=0
        Controls the verbosity when fitting and predicting.

    warm_start : bool, default=False
        When set to ``True``, reuse the solution of the previous call to fit
        and add more estimators to the ensemble, otherwise, just fit a whole
        new forest. See :term:`Glossary <warm_start>` and
        :ref:`tree_ensemble_warm_start` for details.

    Attributes
    ----------
    estimator_ : :class:`~sklearn.tree.ExtraTreeRegressor` instance
        The child estimator template used to create the collection of fitted
        sub-estimators.

        .. versionadded:: 1.2
           `base_estimator_` was renamed to `estimator_`.

    estimators_ : list of :class:`~sklearn.tree.ExtraTreeRegressor` instances
        The collection of fitted sub-estimators.

    feature_importances_ : ndarray of shape (n_features,)
        The feature importances (the higher, the more important the feature).

    n_features_in_ : int
        Number of features seen during :term:`fit`.

        .. versionadded:: 0.24

    n_outputs_ : int
        The number of outputs when ``fit`` is performed.

    one_hot_encoder_ : OneHotEncoder instance
        One-hot encoder used to create the sparse embedding.

    estimators_samples_ : list of arrays
        The subset of drawn samples (i.e., the in-bag samples) for each base
        estimator. Each subset is defined by an array of the indices selected.
    """
    def __init__(self,
                 n_estimators: int = 100,
                 max_depth: int = 5,
                 min_samples_split: Union[int, float] = 2,
                 min_samples_leaf: Union[int, float] = 1,
                 min_weight_fraction_leaf: float = 0.0,
                 max_leaf_nodes: int = None,
                 min_impurity_decrease: float = 0.0,
                 sparse_output: bool = True,
                 n_jobs: int = None,
                 random_state: Union[int, torch.Generator] = None,
                 verbose: int = 0,
                 warm_start: bool = False,
                 device: Union[str, torch.device] = "cpu",
                 dtype: torch.dtype = torch.float,
                 *args,
                 **kwargs,
                 ):
        super().__init__()
        self.n_estimators = n_estimators
        self.max_depth = max_depth
        self.min_samples_split = min_samples_split
        self.min_samples_leaf = min_samples_leaf
        self.min_weight_fraction_leaf = min_weight_fraction_leaf
        self.max_leaf_nodes = max_leaf_nodes
        self.min_impurity_decrease = min_impurity_decrease
        self.sparse_output = sparse_output
        self.n_jobs = n_jobs
        self.random_state = random_state
        self.verbose = verbose
        self.warm_start = warm_start
        self.device = (torch.device(device)
                       if isinstance(device, str) else device)
        self.dtype = dtype
        self.args = args
        self.kwargs = kwargs

        # Fitted attributes
        self.estimator_: Optional[Any] = None
        self.estimators_: List[Any] = []
        self.feature_importances_: Optional[torch.Tensor] = None
        self.n_features_in_: Optional[int] = None
        self.n_outputs_: int = 1
        self.one_hot_encoder_: Optional[Any] = None
        self.estimators_samples_: List[torch.Tensor] = []
        # leaf offsets so each tree's leaf IDs don't collide
        self._leaf_offsets: List[int] = []
        self._n_leaves_per_tree: List[int] = []
        self.fit_status = False

    # ------------------------------------------------------------------
    def _make_tree(self, seed: int) -> Any:
        from ...regression.tree_models.trees import ExtraTreeRegressor
        return ExtraTreeRegressor(
            max_depth=self.max_depth,
            min_samples_split=self.min_samples_split,
            min_samples_leaf=self.min_samples_leaf,
            min_weight_fraction_leaf=self.min_weight_fraction_leaf,
            max_leaf_nodes=self.max_leaf_nodes,
            min_impurity_decrease=self.min_impurity_decrease,
            random_state=seed,
            device=str(self.device),
            dtype=self.dtype,
        )

    # ------------------------------------------------------------------
    def fit(self, X: Any, y: Any = None, sample_weight: Any = None,
            **kwargs) -> "RandomTreesEmbeddings":
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        n_samples, n_features = X_t.shape
        self.n_features_in_ = n_features
        self.n_outputs_ = 1

        gen = _make_generator(self.random_state, self.device)

        # warm_start: keep existing estimators and only add the difference
        start_idx = len(self.estimators_) if self.warm_start else 0
        if not self.warm_start:
            self.estimators_ = []
            self.estimators_samples_ = []
            self._leaf_offsets = []
            self._n_leaves_per_tree = []

        n_to_add = self.n_estimators - start_idx

        if self.verbose:
            print(f"[RandomTreesEmbeddings] Fitting {n_to_add} trees ...")

        for t_idx in range(n_to_add):
            seed = int(torch.randint(0, 2**31 - 1, (1,), generator=gen).item())
            tree = self._make_tree(seed)

            # Random y: standard normal labels force tree to split randomly
            y_rand = torch.randn(n_samples, 1, generator=gen,
                                 device=self.device, dtype=self.dtype)

            tree.fit(X_t, y_rand)

            self.estimators_.append(tree)
            # Record in-bag (all samples when no bootstrap)
            self.estimators_samples_.append(
                torch.arange(n_samples, device=self.device))

            if self.verbose and (t_idx + 1) % 10 == 0:
                print(f"  {t_idx + 1}/{n_to_add} trees done")

        # Pre-compute leaf offsets (needed for one-hot encoding offset)
        total_offset = (sum(self._n_leaves_per_tree)
                        if self._n_leaves_per_tree else 0)
        for tree in self.estimators_[start_idx:]:
            if not tree.is_fit:
                self._leaf_offsets.append(total_offset)
                self._n_leaves_per_tree.append(1)
                total_offset += 1
                continue
            # Dry-run on first sample to count leaves
            _, n_lv = _apply_tree(tree.tree_structure, X_t[:1])
            self._leaf_offsets.append(total_offset)
            self._n_leaves_per_tree.append(n_lv)
            total_offset += n_lv

        # Feature importances: mean across trees
        fi_list = []
        for tree in self.estimators_:
            if hasattr(tree, "feature_importances_"):
                fi = tree.feature_importances_
                if isinstance(fi, torch.Tensor):
                    fi_list.append(fi)
        if fi_list:
            self.feature_importances_ = torch.stack(fi_list).mean(dim=0)
        else:
            self.feature_importances_ = torch.zeros(
                n_features, device=self.device, dtype=self.dtype)

        self.estimator_ = self._make_tree(0)  # template (unfitted)
        self.fit_status = True
        return self

    # ------------------------------------------------------------------
    def apply(self, X: Any) -> torch.Tensor:
        """
        Return leaf indices for X across all trees.

        Returns
        -------
        X_leaves : (n_samples, n_estimators) LongTensor
        """
        if not self.fit_status:
            raise RuntimeError("Call fit() before apply().")
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        n_samples = X_t.shape[0]
        X_leaves = torch.zeros(n_samples, len(self.estimators_),
                               dtype=torch.long, device=self.device)
        for t_idx, tree in enumerate(self.estimators_):
            if not tree.is_fit:
                continue
            leaf_ids, _ = _apply_tree(tree.tree_structure, X_t)
            X_leaves[:, t_idx] = leaf_ids

        return X_leaves

    # ------------------------------------------------------------------
    def transform(self, X: Any, **kwargs) -> torch.Tensor:
        """
        Return a (n_samples, n_leaves_total) one-hot encoded embedding.

        Each sample maps to the leaf it falls into per tree.
        If ``sparse_output=True``, returns a sparse tensor.
        """
        if not self.fit_status:
            raise RuntimeError("Call fit() before transform().")
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        n_samples = X_t.shape[0]
        n_total_leaves = sum(self._n_leaves_per_tree)

        out = torch.zeros(n_samples, n_total_leaves,
                          dtype=self.dtype, device=self.device)

        for t_idx, tree in enumerate(self.estimators_):
            if not tree.is_fit:
                continue
            leaf_ids, _ = _apply_tree(tree.tree_structure, X_t)
            offset = int(self._leaf_offsets[t_idx])
            rows = torch.arange(int(n_samples), device=self.device, dtype=torch.long)
            out[rows, (leaf_ids + offset).long()] = 1.0

        if self.sparse_output:
            return out.to_sparse()
        return out

    # ------------------------------------------------------------------
    def fit_transform(self, X: Any, y: Any = None,
                      sample_weight: Any = None, **kwargs) -> torch.Tensor:
        return self.fit(X, y, sample_weight, **kwargs).transform(X, **kwargs)

    # ------------------------------------------------------------------
    def forward(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            self.fit(X, **kwargs)
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def predict(self, X: Any, **kwargs) -> torch.Tensor:
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def score(self, X: Any, y: Any = None, **kwargs) -> float:
        return 0.0



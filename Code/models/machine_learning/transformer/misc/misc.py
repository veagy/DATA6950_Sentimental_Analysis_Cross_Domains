class ColumnTransformer(MLTransform):
    """
    Applies transformers to columns of an array or pandas DataFrame.

    This estimator allows different columns or column subsets of the input
    to be transformed separately and the features generated by each transformer
    will be concatenated to form a single feature space.
    This is useful for heterogeneous or columnar data, to combine several
    feature extraction mechanisms or transformations into a single transformer.

    Read more in the :ref:`User Guide <column_transformer>`.

    .. versionadded:: 0.20

    Parameters
    ----------
    transformers : list of tuples
        List of (name, transformer, columns) tuples specifying the
        transformer objects to be applied to subsets of the data.

        name : str
            Like in Pipeline and FeatureUnion, this allows the transformer and
            its parameters to be set using ``set_params`` and searched in grid
            search.
        transformer : {'drop', 'passthrough'} or estimator
            Estimator must support :term:`fit` and :term:`transform`.
            Special-cased strings 'drop' and 'passthrough' are accepted as
            well, to indicate to drop the columns or to pass them through
            untransformed, respectively.
        columns :  str, array-like of str, int, array-like of int, \
                array-like of bool, slice or callable
            Indexes the data on its second axis. Integers are interpreted as
            positional columns, while strings can reference DataFrame columns
            by name.  A scalar string or int should be used where
            ``transformer`` expects X to be a 1d array-like (vector),
            otherwise a 2d array will be passed to the transformer.
            A callable is passed the input data `X` and can return any of the
            above. To select multiple columns by name or dtype, you can use
            :obj:`make_column_selector`.

    remainder : {'drop', 'passthrough'} or estimator, default='drop'
        By default, only the specified columns in `transformers` are
        transformed and combined in the output, and the non-specified
        columns are dropped. (default of ``'drop'``).
        By specifying ``remainder='passthrough'``, all remaining columns that
        were not specified in `transformers`, but present in the data passed
        to `fit` will be automatically passed through. This subset of columns
        is concatenated with the output of the transformers. For dataframes,
        extra columns not seen during `fit` will be excluded from the output
        of `transform`.
        By setting ``remainder`` to be an estimator, the remaining
        non-specified columns will use the ``remainder`` estimator. The
        estimator must support :term:`fit` and :term:`transform`.
        Note that using this feature requires that the DataFrame columns
        input at :term:`fit` and :term:`transform` have identical order.

    sparse_threshold : float, default=0.3
        If the output of the different transformers contains sparse matrices,
        these will be stacked as a sparse matrix if the overall density is
        lower than this value. Use ``sparse_threshold=0`` to always return
        dense.  When the transformed output consists of all dense data, the
        stacked result will be dense, and this keyword will be ignored.

    n_jobs : int, default=None
        Number of jobs to run in parallel.
        ``None`` means 1 unless in a :obj:`joblib.parallel_backend` context.
        ``-1`` means using all processors. See :term:`Glossary <n_jobs>`
        for more details.

    transformer_weights : dict, default=None
        Multiplicative weights for features per transformer. The output of the
        transformer is multiplied by these weights. Keys are transformer names,
        values the weights.

    verbose : bool, default=False
        If True, the time elapsed while fitting each transformer will be
        printed as it is completed.

    verbose_feature_names_out : bool, str or Callable[[str, str], str], default=True

        - If True, :meth:`ColumnTransformer.get_feature_names_out` will prefix
          all feature names with the name of the transformer that generated that
          feature. It is equivalent to setting
          `verbose_feature_names_out="{transformer_name}__{feature_name}"`.
        - If False, :meth:`ColumnTransformer.get_feature_names_out` will not
          prefix any feature names and will error if feature names are not
          unique.
        - If ``Callable[[str, str], str]``,
          :meth:`ColumnTransformer.get_feature_names_out` will rename all the features
          using the name of the transformer. The first argument of the callable is the
          transformer name and the second argument is the feature name. The returned
          string will be the new feature name.
        - If ``str``, it must be a string ready for formatting. The given string will
          be formatted using two field names: ``transformer_name`` and ``feature_name``.
          e.g. ``"{feature_name}__{transformer_name}"``. See :meth:`str.format` method
          from the standard library for more info.

        .. versionadded:: 1.0

        .. versionchanged:: 1.6
            `verbose_feature_names_out` can be a callable or a string to be formatted.

    force_int_remainder_cols : bool, default=False
        This parameter has no effect.

        .. note::
            If you do not access the list of columns for the remainder columns
            in the `transformers_` fitted attribute, you do not need to set
            this parameter.

        .. versionadded:: 1.5

        .. versionchanged:: 1.7
           The default value for `force_int_remainder_cols` will change from
           `True` to `False` in version 1.7.

        .. deprecated:: 1.7
           `force_int_remainder_cols` is deprecated and will be removed in 1.9.

    Attributes
    ----------
    transformers_ : list
        The collection of fitted transformers as tuples of (name,
        fitted_transformer, column). `fitted_transformer` can be an estimator,
        or `'drop'`; `'passthrough'` is replaced with an equivalent
        :class:`~sklearn.preprocessing.FunctionTransformer`. In case there were
        no columns selected, this will be the unfitted transformer. If there
        are remaining columns, the final element is a tuple of the form:
        ('remainder', transformer, remaining_columns) corresponding to the
        ``remainder`` parameter. If there are remaining columns, then
        ``len(transformers_)==len(transformers)+1``, otherwise
        ``len(transformers_)==len(transformers)``.

        .. versionadded:: 1.7
            The format of the remaining columns now attempts to match that of the other
            transformers: if all columns were provided as column names (`str`), the
            remaining columns are stored as column names; if all columns were provided
            as mask arrays (`bool`), so are the remaining columns; in all other cases
            the remaining columns are stored as indices (`int`).

    named_transformers_ : :class:`~sklearn.utils.Bunch`
        Read-only attribute to access any transformer by given name.
        Keys are transformer names and values are the fitted transformer
        objects.

    sparse_output_ : bool
        Boolean flag indicating whether the output of ``transform`` is a
        sparse matrix or a dense numpy array, which depends on the output
        of the individual transformers and the `sparse_threshold` keyword.

    output_indices_ : dict
        A dictionary from each transformer name to a slice, where the slice
        corresponds to indices in the transformed output. This is useful to
        inspect which transformer is responsible for which transformed
        feature(s).

        .. versionadded:: 1.0

    n_features_in_ : int
        Number of features seen during :term:`fit`. Only defined if the
        underlying transformers expose such an attribute when fit.
    """
    def __init__(self,
                 transformers: Union[List[Union[list, tuple]],
                    Tuple[List[Union[list, tuple]]],
                    torch.Tensor,
                    None] = None,
                 name: str = None,
                 transformer: Union[Literal["drop", "passthrough"], MLModule] = None,
                 columns: Union[str, int, slice, List[Union[str, int, bool]],
                    Tuple[Union[str, int, bool]], torch.Tensor, Callable, nn.Module] = None,
                 remainder: Union[Literal["drop", "passthrough"], MLModule] = "drop",
                 sparse_threshold: float = 0.3,
                 n_jobs: int = None,
                 transformer_weights: dict = None,
                 verbose: bool = False,
                 verbose_feature_names_out: Union[bool, str, Callable[[str, str], str]] = True,
                 device: Union[str, torch.device] = "cpu",
                 dtype: torch.dtype = torch.float,
                 *args,
                 **kwargs,
                 ):
        super().__init__()
        # If a single (name, transformer, columns) triple is provided as separate
        # args, merge it into the transformers list.
        self.transformers = list(transformers) if transformers is not None else []
        if name is not None and transformer is not None and columns is not None:
            self.transformers.append((name, transformer, columns))

        self.name = name
        self.transformer = transformer
        self.columns = columns
        self.remainder = remainder
        self.sparse_threshold = sparse_threshold
        self.n_jobs = n_jobs
        self.transformer_weights = transformer_weights or {}
        self.verbose = verbose
        self.verbose_feature_names_out = verbose_feature_names_out
        self.device = (torch.device(device)
                       if isinstance(device, str) else device)
        self.dtype = dtype
        self.args = args
        self.kwargs = kwargs

        # Fitted attributes
        self.transformers_: List[Tuple] = []
        self.named_transformers_: Dict[str, Any] = {}
        self.sparse_output_: bool = False
        self.output_indices_: Dict[str, slice] = {}
        self.n_features_in_: Optional[int] = None
        self.fit_status = False

    # ------------------------------------------------------------------
    def _get_transformer_in(self, t_name: str, t: Any, col_idx: List[int],
                            X_t: torch.Tensor) -> torch.Tensor:
        """Extract the column slice for a single transformer."""
        sub = X_t[:, col_idx]
        # Scalar column: keep 2-D
        return sub

    def _fit_one(self, t_name: str, t: Any, col_idx: List[int],
                 X_t: torch.Tensor, y: Any = None):
        """Fit a single transformer and return the fitted object."""
        if t == "drop":
            return "drop"
        sub = self._get_transformer_in(t_name, t, col_idx, X_t)
        if t == "passthrough":
            return "passthrough"
        t0 = time.time() if self.verbose else None
        t.fit(sub, y)
        if self.verbose:
            print(f"[ColumnTransformer] Fitting {t_name!r} done in "
                  f"{time.time() - t0:.3f}s")
        return t

    def _transform_one(self, t_name: str, t: Any, col_idx: List[int],
                       X_t: torch.Tensor) -> Optional[torch.Tensor]:
        """Transform X using a single fitted transformer."""
        if t == "drop":
            return None
        sub = self._get_transformer_in(t_name, t, col_idx, X_t)
        if t == "passthrough":
            return sub
        result = t.transform(sub)
        if isinstance(result, torch.Tensor) and result.is_sparse:
            result = result.to_dense()
        result = result.to(dtype=self.dtype, device=self.device)
        # Apply weight
        w = self.transformer_weights.get(t_name)
        if w is not None:
            result = result * w
        return result

    # ------------------------------------------------------------------
    def fit(self, X: Any, y: Any = None, **kwargs) -> "ColumnTransformer":
        feature_names = _get_feature_names(X)
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)
        n_samples, n_cols = X_t.shape
        self.n_features_in_ = n_cols

        # Collect all specified column indices
        all_specified: set = set()
        self.transformers_ = []
        self.named_transformers_ = {}

        for entry in self.transformers:
            t_name, t, cols = entry[0], entry[1], entry[2]
            col_idx = _resolve_columns(X_t, cols, feature_names)
            all_specified.update(col_idx)
            fitted_t = self._fit_one(t_name, t, col_idx, X_t, y)
            self.transformers_.append((t_name, fitted_t, col_idx))
            self.named_transformers_[t_name] = fitted_t

        # Handle remainder columns
        remainder_cols = [i for i in range(n_cols) if i not in all_specified]
        if remainder_cols:
            rem = self.remainder
            if rem == "drop":
                fitted_rem = "drop"
            elif rem == "passthrough":
                fitted_rem = "passthrough"
            else:
                # estimator
                fitted_rem = self._fit_one("remainder", rem, remainder_cols, X_t, y)
            self.transformers_.append(("remainder", fitted_rem, remainder_cols))
            self.named_transformers_["remainder"] = fitted_rem

        self.fit_status = True
        return self

    # ------------------------------------------------------------------
    def transform(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            raise RuntimeError("Call fit() before transform().")
        feature_names = _get_feature_names(X)
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        parts: List[torch.Tensor] = []
        col_offset = 0
        self.output_indices_ = {}

        for t_name, t, col_idx in self.transformers_:
            result = self._transform_one(t_name, t, col_idx, X_t)
            if result is None:
                continue
            if result.ndim == 1:
                result = result.unsqueeze(1)
            n_out = result.shape[1]
            self.output_indices_[t_name] = slice(col_offset, col_offset + n_out)
            col_offset += n_out
            parts.append(result)

        if not parts:
            return torch.zeros(X_t.shape[0], 0,
                               dtype=self.dtype, device=self.device)

        out = torch.cat(parts, dim=1)

        # Determine sparse_output_
        density = out.count_nonzero().item() / max(out.numel(), 1)
        self.sparse_output_ = density < self.sparse_threshold
        if self.sparse_output_:
            return out.to_sparse()
        return out

    # ------------------------------------------------------------------
    def fit_transform(self, X: Any, y: Any = None, **kwargs) -> torch.Tensor:
        return self.fit(X, y, **kwargs).transform(X, **kwargs)

    # ------------------------------------------------------------------
    def get_feature_names_out(
        self, input_features: Optional[List[str]] = None
    ) -> List[str]:
        if not self.fit_status:
            raise RuntimeError("Call fit() before get_feature_names_out().")

        vfno = self.verbose_feature_names_out
        out_names: List[str] = []

        for t_name, t, col_idx in self.transformers_:
            if t == "drop":
                continue
            if t == "passthrough":
                sub_names = ([input_features[i] for i in col_idx]
                             if input_features else [f"x{i}" for i in col_idx])
            elif hasattr(t, "get_feature_names_out"):
                sub_names = list(t.get_feature_names_out())
            else:
                sub_names = [f"x{i}" for i in col_idx]

            for fn in sub_names:
                if vfno is True:
                    out_names.append(f"{t_name}__{fn}")
                elif vfno is False:
                    out_names.append(fn)
                elif isinstance(vfno, str):
                    out_names.append(
                        vfno.format(transformer_name=t_name, feature_name=fn))
                elif callable(vfno):
                    out_names.append(vfno(t_name, fn))
                else:
                    out_names.append(fn)

        return out_names

    # ------------------------------------------------------------------
    def forward(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            self.fit(X, **kwargs)
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def predict(self, X: Any, **kwargs) -> torch.Tensor:
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def score(self, X: Any, y: Any = None, **kwargs) -> float:
        return 0.0



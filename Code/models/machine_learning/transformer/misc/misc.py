class RadiusNeighborsTransformer(MLTransform):
    """
    Transform X into a (weighted) graph of neighbors nearer than a radius.

    The transformed data is a sparse graph as returned by
    `radius_neighbors_graph`.

    Read more in the :ref:`User Guide <neighbors_transformer>`.

    .. versionadded:: 0.22

    Parameters
    ----------
    mode : {'distance', 'connectivity'}, default='distance'
        Type of returned matrix: 'connectivity' will return the connectivity
        matrix with ones and zeros, and 'distance' will return the distances
        between neighbors according to the given metric.

    radius : float, default=1.0
        Radius of neighborhood in the transformed sparse graph.

    algorithm : {'auto', 'ball_tree', 'kd_tree', 'brute'}, default='auto'
        Algorithm used to compute the nearest neighbors:

        - 'ball_tree' will use :class:`BallTree`
        - 'kd_tree' will use :class:`KDTree`
        - 'brute' will use a brute-force search.
        - 'auto' will attempt to decide the most appropriate algorithm
          based on the values passed to :meth:`fit` method.

        Note: fitting on sparse input will override the setting of
        this parameter, using brute force.

    leaf_size : int, default=30
        Leaf size passed to BallTree or KDTree.  This can affect the
        speed of the construction and query, as well as the memory
        required to store the tree.  The optimal value depends on the
        nature of the problem.

    metric : str or callable, default='minkowski'
        Metric to use for distance computation. Default is "minkowski", which
        results in the standard Euclidean distance when p = 2. See the
        documentation of `scipy.spatial.distance
        <https://docs.scipy.org/doc/scipy/reference/spatial.distance.html>`_ and
        the metrics listed in
        :class:`~sklearn.metrics.pairwise.distance_metrics` for valid metric
        values.

        If metric is a callable function, it takes two arrays representing 1D
        vectors as inputs and must return one value indicating the distance
        between those vectors. This works for Scipy's metrics, but is less
        efficient than passing the metric name as a string.

        Distance matrices are not supported.

    p : float, default=2
        Parameter for the Minkowski metric from
        sklearn.metrics.pairwise.pairwise_distances. When p = 1, this is
        equivalent to using manhattan_distance (l1), and euclidean_distance
        (l2) for p = 2. For arbitrary p, minkowski_distance (l_p) is used.
        This parameter is expected to be positive.

    metric_params : dict, default=None
        Additional keyword arguments for the metric function.

    n_jobs : int, default=None
        The number of parallel jobs to run for neighbors search.
        If ``-1``, then the number of jobs is set to the number of CPU cores.

    Attributes
    ----------
    effective_metric_ : str or callable
        The distance metric used. It will be same as the `metric` parameter
        or a synonym of it, e.g. 'euclidean' if the `metric` parameter set to
        'minkowski' and `p` parameter set to 2.

    effective_metric_params_ : dict
        Additional keyword arguments for the metric function. For most metrics
        will be same with `metric_params` parameter, but may also contain the
        `p` parameter value if the `effective_metric_` attribute is set to
        'minkowski'.

    n_features_in_ : int
        Number of features seen during :term:`fit`.

        .. versionadded:: 0.24

    n_samples_fit_ : int
        Number of samples in the fitted data.
    """

    from ...regression.knn.knn import BallTree, KDTree

    def __init__(self,
                 mode: Literal["distance", "connectivity"] = 'distance',
                 radius: float = 1.0,
                 algorithm: Union[Literal["auto", "ball_tree", "kd_tree", "brute"],
                 Callable, nn.Module] = 'auto',
                 leaf_size: int = 30,
                 metric: Union[str, Callable, nn.Module] = 'minkowski',
                 p: float = 2,
                 metric_params: dict = None,
                 n_jobs: int = None,
                 device: Union[str, torch.device] = "cpu",
                 dtype: torch.dtype = torch.float,
                 *args,
                 **kwargs,
                 ):
        super().__init__()
        if metric_params is None:
            metric_params = {}
        metric_params["p"] = p
        from ....utils.utils import MLCluster
        self.metric = MLCluster()._create_metric(metric, metric_params).metric

        self.mode = mode
        self.radius = radius
        self.algorithm = algorithm
        self.leaf_size = leaf_size
        self._metric_name = metric
        self.p = p
        self.metric_params = metric_params
        self.n_jobs = n_jobs
        self.device = (torch.device(device)
                       if isinstance(device, str) else device)
        self.dtype = dtype
        self.args = args
        self.kwargs = kwargs

        # Fitted attributes
        self._fit_X: Optional[torch.Tensor] = None
        self._tree: Optional[Any] = None
        self._algorithm: Optional[str] = None
        self.effective_metric_: Any = metric
        self.effective_metric_params_: Dict = metric_params
        self.n_features_in_: Optional[int] = None
        self.n_samples_fit_: Optional[int] = None
        self.fit_status = False

    # ------------------------------------------------------------------
    def fit(self, X: Any, y: Any = None,
            **kwargs) -> "RadiusNeighborsTransformer":
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        n_samples, n_features = X_t.shape
        self.n_features_in_ = n_features
        self.n_samples_fit_ = n_samples
        self._fit_X = X_t

        alg = self.algorithm
        self._algorithm = "brute" if (alg == "auto" or callable(alg)
                                      or isinstance(alg, nn.Module)) else alg

        if self._algorithm == "ball_tree":
            from ...regression.knn.knn import BallTree
            self._tree = BallTree(X_t, leaf_size=self.leaf_size,
                                  metric=self.metric,
                                  device=str(self.device), dtype=self.dtype)
        elif self._algorithm == "kd_tree":
            from ...regression.knn.knn import KDTree
            self._tree = KDTree(X_t, leaf_size=self.leaf_size,
                                metric=self.metric,
                                device=str(self.device), dtype=self.dtype)
        else:
            self._tree = None

        self.fit_status = True
        return self

    # ------------------------------------------------------------------
    def _radius_neighbors(self, X_t: torch.Tensor
                          ) -> Tuple[List[torch.Tensor], List[torch.Tensor]]:
        """Return (distances_list, indices_list) for each query point."""
        all_dists = self.metric(X_t, self._fit_X)   # (n_test, n_train)
        mask = all_dists <= self.radius

        dists_list, inds_list = [], []
        for i in range(X_t.shape[0]):
            row = mask[i]
            d = all_dists[i][row]
            idx = row.nonzero(as_tuple=True)[0]
            dists_list.append(d)
            inds_list.append(idx)
        return dists_list, inds_list

    # ------------------------------------------------------------------
    def transform(self, X: Any, **kwargs) -> torch.Tensor:
        """
        Return a (n_samples, n_samples_fit_) adjacency matrix.

        Entry [i, j] is non-zero if sample j is within `radius` of query i.
        Values are distances (mode='distance') or ones (mode='connectivity').
        """
        if not self.fit_status:
            raise RuntimeError("Call fit() before transform().")
        X_t = _to_tensor(X, self.dtype, self.device)
        if X_t.ndim == 1:
            X_t = X_t.unsqueeze(1)

        n_test = X_t.shape[0]
        n_train = self.n_samples_fit_

        graph = torch.zeros(n_test, n_train, dtype=self.dtype, device=self.device)

        if self._tree is not None and hasattr(self._tree, "query_radius"):
            try:
                dists_list, inds_list = self._tree.query_radius(
                    X_t, r=self.radius, return_distance=True, sort_results=False)
            except Exception:
                dists_list, inds_list = self._radius_neighbors(X_t)
        else:
            dists_list, inds_list = self._radius_neighbors(X_t)

        for i, (d, idx) in enumerate(zip(dists_list, inds_list)):
            if self.mode == "distance":
                graph[i, idx] = d.to(self.dtype)
            else:
                graph[i, idx] = 1.0

        return graph

    # ------------------------------------------------------------------
    def fit_transform(self, X: Any, y: Any = None, **kwargs) -> torch.Tensor:
        return self.fit(X, y, **kwargs).transform(X, **kwargs)

    # ------------------------------------------------------------------
    def forward(self, X: Any, **kwargs) -> torch.Tensor:
        if not self.fit_status:
            self.fit(X, **kwargs)
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def predict(self, X: Any, **kwargs) -> torch.Tensor:
        return self.transform(X, **kwargs)

    # ------------------------------------------------------------------
    def score(self, X: Any, y: Any = None, **kwargs) -> float:
        return 0.0



def _to_tensor(X: Any, dtype: torch.dtype, device: torch.device) -> torch.Tensor:
    """Convert array-like / DataFrame / Tensor to a 2-D float Tensor."""
    try:
        import pandas as pd  # pyright: ignore[reportMissingImports]
        if isinstance(X, pd.DataFrame):
            return torch.tensor(X.values, dtype=dtype, device=device)
        if isinstance(X, pd.Series):
            return torch.tensor(X.values, dtype=dtype, device=device).unsqueeze(1)
    except ImportError:
        pass
    if isinstance(X, torch.Tensor):
        return X.to(dtype=dtype, device=device)
    return torch.tensor(np.array(X), dtype=dtype, device=device)


def _get_feature_names(X: Any) -> Optional[List[str]]:
    """Return column names if X is a DataFrame, else None."""
    try:
        import pandas as pd  # pyright: ignore[reportMissingImports]
        if isinstance(X, pd.DataFrame):
            return list(X.columns)
    except ImportError:
        pass
    return None


def _resolve_columns(X_t: torch.Tensor, columns: Any,
                     feature_names: Optional[List[str]]) -> List[int]:
    """
    Resolve a column specification to a list of integer indices.

    Supports: int, str, slice, list/tuple of int/str/bool,
    bool Tensor/array, callable.
    """
    n_cols = X_t.shape[1]

    if callable(columns):
        columns = columns(X_t)

    if isinstance(columns, slice):
        return list(range(*columns.indices(n_cols)))

    if isinstance(columns, int):
        return [columns]

    if isinstance(columns, str):
        if feature_names is None:
            raise ValueError("String column selector requires a DataFrame input.")
        return [feature_names.index(columns)]

    if isinstance(columns, torch.Tensor):
        if columns.dtype == torch.bool:
            return columns.nonzero(as_tuple=True)[0].tolist()
        return columns.long().tolist()

    if isinstance(columns, (list, tuple, np.ndarray)):
        arr = list(columns)
        if len(arr) == 0:
            return []
        first = arr[0]
        if isinstance(first, bool) or (isinstance(first, (int, np.integer))
                                       and all(isinstance(v, (bool, np.bool_)) for v in arr)):
            return [i for i, v in enumerate(arr) if v]
        result: List[int] = []
        for c in arr:
            if isinstance(c, (bool, np.bool_)):
                # boolean array – rebuild
                return [i for i, v in enumerate(arr) if v]
            elif isinstance(c, str):
                if feature_names is None:
                    raise ValueError(
                        "String column selectors require a DataFrame input.")
                result.append(feature_names.index(c))
            else:
                result.append(int(c))
        return result

    raise ValueError(f"Cannot interpret columns={columns!r}.")


def _make_generator(random_state: Union[int, torch.Generator, None],
                    device: torch.device) -> torch.Generator:
    gen = torch.Generator(device=device)
    if isinstance(random_state, torch.Generator):
        return random_state
    if isinstance(random_state, int):
        gen.manual_seed(random_state)
    else:
        gen.seed()
    return gen


